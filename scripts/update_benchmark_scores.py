#!/usr/bin/env python3
"""Regenerate llmproxy/benchmark_scores.json, the bundled benchmark snapshot.

The flagship refresh fetches scores live; this snapshot is what it falls back
to when a source is unreachable, so a deployment never ranks the tier on
nothing. Only sources whose licence permits redistribution are written (see
``llmproxy.flagship.SNAPSHOT_SOURCES``), each with its attribution. A source
that fails to fetch keeps its previous snapshot rather than being emptied.

    python scripts/update_benchmark_scores.py
"""

from __future__ import annotations

import datetime
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from llmproxy import flagship  # noqa: E402

SOURCES = {
    "epoch_eci": {
        "name": "Epoch AI Capabilities Index (ECI)",
        "url": "https://epoch.ai/benchmarks",
        "license": "CC-BY-4.0",
        "attribution": "Epoch AI, 'Capabilities & benchmarking'. Published online at "
                       "epoch.ai. Retrieved from https://epoch.ai/benchmarks",
        "fetch": flagship.fetch_epoch_eci_scores,
    },
    "lmarena_agent": {
        "name": "LMArena agent leaderboard (overall score)",
        "url": "https://huggingface.co/datasets/lmarena-ai/leaderboard-dataset",
        "license": "CC-BY-4.0",
        "attribution": "LMArena, leaderboard-dataset (agent), Hugging Face",
        "fetch": lambda: flagship.fetch_lmarena_scores("agent", "score"),
    },
    "lmarena_text": {
        "name": "LMArena text leaderboard (overall rating)",
        "url": "https://huggingface.co/datasets/lmarena-ai/leaderboard-dataset",
        "license": "CC-BY-4.0",
        "attribution": "LMArena, leaderboard-dataset (text), Hugging Face",
        "fetch": lambda: flagship.fetch_lmarena_scores("text", "rating"),
    },
}


def main() -> int:
    path = flagship.BENCHMARK_SNAPSHOT_PATH
    try:
        previous = json.loads(path.read_text(encoding="utf-8")).get("sources", {})
    except (OSError, ValueError):
        previous = {}
    out: dict = {}
    failed = 0
    for key, meta in SOURCES.items():
        block = {k: v for k, v in meta.items() if k != "fetch"}
        try:
            scores = meta["fetch"]()
        except Exception as e:  # noqa: BLE001 — keep the previous snapshot
            scores = {}
            print(f"{key}: fetch failed ({type(e).__name__}: {e})", file=sys.stderr)
        if scores:
            block["retrieved_at"] = datetime.datetime.now(datetime.UTC).date().isoformat()
            block["scores"] = dict(sorted((k, round(v, 4)) for k, v in scores.items()))
        elif key in previous:
            failed += 1
            block = previous[key]
        else:
            failed += 1
            continue
        out[key] = block
        print(f"{key}: {len(block.get('scores', {}))} model(s)")
    doc = {
        "_comment": "Generated by scripts/update_benchmark_scores.py. Bundled fallback "
                    "for the flagship tier's benchmark sources; each source is "
                    "redistributed under its stated licence with attribution.",
        "sources": out,
    }
    path.write_text(json.dumps(doc, indent=1, sort_keys=False) + "\n", encoding="utf-8")
    return 1 if failed == len(SOURCES) else 0


if __name__ == "__main__":
    sys.exit(main())
